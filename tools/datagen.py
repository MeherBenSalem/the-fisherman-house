def loader_data(d: Dialect):
    """The rod's extra loot on Forge and NeoForge (Fabric adds the same pool in code)."""
    for loader in LOADERS[d.v]:
        if loader == 'fabric':
            continue
        data = REPO / d.v / loader / 'src/main/resources/data'
        shutil.rmtree(data, ignore_errors=True)
        if loader == 'forge':
            write(data / 'forge/loot_modifiers/global_loot_modifiers.json', {'replace': False, 'entries': [f'{NS}:rod_extras']})
            modifier = {'type': f'{NS}:add_table', 'conditions': [{'condition': 'forge:loot_table_id', 'loot_table_id': 'minecraft:gameplay/fishing'}],
                        'table': f'{NS}:gameplay/rod_extras'}
        elif d.modifier:
            modifier = {'type': 'neoforge:add_table', 'condition': {'type': 'neoforge:loot_table_id', 'loot_table_id': 'minecraft:gameplay/fishing'},
                        'table': f'{NS}:gameplay/rod_extras'}
        else:
            modifier = {'type': 'neoforge:add_table', 'conditions': [{'condition': 'neoforge:loot_table_id', 'loot_table_id': 'minecraft:gameplay/fishing'}],
                        'table': f'{NS}:gameplay/rod_extras'}
            if d.v == '1.21.1':
                write(data / 'neoforge/loot_modifiers/global_loot_modifiers.json', {'replace': False, 'entries': [f'{NS}:rod_extras']})
        write(data / NS / 'loot_modifiers/rod_extras.json', modifier)


def generate(v):
    d = Dialect(v)
    res = REPO / v / 'common/src/main/resources'
    for stale in (res / 'assets' / NS, res / 'data'):
        shutil.rmtree(stale, ignore_errors=True)
    write(res / 'pack.mcmeta', {'pack': {'description': "Fisherman's Coast resources", **PACK[v]}})
    data = res / 'data' / NS
    lang = dict(LANG)
    for name, table in loot_tables(d).items():
        write(data / d.dir('loot_table') / f'{name}.json', table)
    for name, adv in advancements(d, lang).items():
        write(data / d.dir('advancement') / f'{name}.json', adv)
    for rid, (pattern, key, result, count, item) in RECIPES.items():
        write(data / d.dir('recipe') / f'{rid}.json', d.recipe(pattern, key, result, count))
        write(data / d.dir('advancement') / 'recipes/misc' / f'{rid}.json', d.unlock(f'{NS}:{rid}', item))
    meta = json.loads((TOOLS / 'assets/structures/sites.json').read_text())
    for sid, (name, biomes, spacing, separation, salt, *_r) in STRUCTURES.items():
        lang[f'structure.{NS}.{sid}'] = name
        if sid not in meta:
            continue
        write(data / 'worldgen/structure' / f'{sid}.json', structure_json(sid, meta))
        write(data / 'worldgen/structure_set' / f'{sid}.json', {
            'structures': [{'structure': f'{NS}:{sid}', 'weight': 1}],
            'placement': {'type': 'minecraft:random_spread', 'spacing': spacing, 'separation': separation, 'salt': salt,
                          'exclusion_zone': {'other_set': 'minecraft:villages', 'chunk_count': VILLAGE_CLEARANCE}}})
        write(data / 'tags/worldgen/biome/has_structure' / f'{sid}.json', {'values': biomes})
        (data / d.dir('structure')).mkdir(parents=True, exist_ok=True)
        template = TEMPLATES.get(sid, sid)
        shutil.copy(TOOLS / 'assets/structures' / f'{template}.nbt', data / d.dir('structure') / f'{template}.nbt')
    shutil.copy(LEGACY_TEMPLATE, data / d.dir('structure') / 'fisherman_house.nbt')
    built = [s for s in STRUCTURES if s in meta]
    write(data / 'tags/worldgen/structure/coastal.json', {'values': [f'{NS}:{s}' for s in built]})
    write(data / 'tags/worldgen/structure/on_bottle_maps.json',
          {'values': [{'id': f'{NS}:sunken_trawler', 'required': False}]})
    for place, values in POT_PLACES.items():
        write(data / 'tags/worldgen/biome/crab_pot' / f'{place}.json', {'values': values})
    write(data / d.dir('tags/item') / 'raw_fish.json', {'values': ['minecraft:cod', 'minecraft:salmon']})
    mc = res / 'data' / 'minecraft'
    write(mc / d.dir('tags/block') / 'climbable.json', {'replace': False, 'values': [f'{NS}:fishing_net']})
    write(mc / d.dir('tags/block') / 'mineable/axe.json', {'replace': False, 'values': [f'{NS}:crab_pot', f'{NS}:fishing_net']})
    assets(d, res)
    write(res / 'assets' / NS / 'lang/en_us.json', dict(sorted(lang.items())))
    loader_data(d)


def main():
    for v in VERSIONS:
        if (REPO / v).is_dir():
            generate(v)
            print('generated', v)


if __name__ == '__main__':
    main()
