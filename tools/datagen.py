def box(frm, to, tex, faces=('north', 'south', 'east', 'west', 'up', 'down'), uv=None):
    out = {'from': frm, 'to': to, 'faces': {}}
    for f in faces:
        if f in ('north', 'south'):
            u = [frm[0], 16 - to[1], to[0], 16 - frm[1]]
        elif f in ('east', 'west'):
            u = [frm[2], 16 - to[1], to[2], 16 - frm[1]]
        else:
            u = [frm[0], frm[2], to[0], to[2]]
        out['faces'][f] = {'uv': uv or u, 'texture': tex}
    return out


