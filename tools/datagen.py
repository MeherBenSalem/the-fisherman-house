class Dialect:
    def __init__(self, v):
        self.v = v
        self.legacy = v == '1.20.1'
        self.v26 = v.startswith('26.')
        self.namespaced_predicates = v in ('26.2', '26.3')
        self.modifier = v == '26.3'

    def dir(self, kind):
        plural = {'loot_table': 'loot_tables', 'recipe': 'recipes', 'advancement': 'advancements', 'structure': 'structures',
                  'tags/block': 'tags/blocks', 'tags/item': 'tags/items'}
        return plural.get(kind, kind) if self.legacy else kind

    # Loot
    def fn(self, kind, **fields):
        return {('type' if self.modifier else 'function'): f'minecraft:{kind}', **fields}

    def cond(self, kind, **fields):
        return {('type' if self.modifier else 'condition'): f'minecraft:{kind}', **fields}

    def with_functions(self, entry, functions):
        if functions:
            if self.modifier:
                entry['modifier'] = functions[0] if len(functions) == 1 else functions
            else:
                entry['functions'] = functions
        return entry

    def with_conditions(self, entry, conditions):
        if conditions:
            if self.modifier:
                entry['condition'] = conditions[0] if len(conditions) == 1 else {'type': 'minecraft:all_of', 'terms': conditions}
            else:
                entry['conditions'] = conditions
        return entry

    @staticmethod
    def uniform(lo, hi):
        return {'type': 'minecraft:uniform', 'min': lo, 'max': hi}

    def item(self, x):
        if 'empty' in x:
            return {'type': 'minecraft:empty', 'weight': x['empty']}
        name = x['item'] if ':' in x['item'] else 'minecraft:' + x['item']
        out = {'type': 'minecraft:item', 'name': name, 'weight': x['weight']}
        if x['quality']:
            out['quality'] = x['quality']
        functions = []
        if isinstance(x['count'], tuple):
            functions.append(self.fn('set_count', count=self.uniform(*x['count'])))
        elif x['count']:
            functions.append(self.fn('set_count', count=x['count']))
        extra = x['extra']
        if isinstance(extra, tuple) and extra[0] == 'levels':
            functions.append(self.fn('enchant_with_levels', levels=self.uniform(extra[1], extra[2])))
        elif extra == 'water_breathing':
            functions.append(self.fn('set_potion', id='minecraft:water_breathing'))
        return self.with_functions(out, functions)

    def table_ref(self, table, weight, quality):
        key = 'name' if self.legacy else 'value'
        out = {'type': 'minecraft:loot_table', key: table, 'weight': weight}
        if quality:
            out['quality'] = quality
        return out

    def trawler_map(self, weight):
        tag = f'{NS}:on_bottle_maps'
        functions = [self.fn('exploration_map', destination=f'#{tag}' if self.modifier else tag,
                             decoration='red_x' if self.legacy else 'minecraft:red_x', zoom=1, search_radius=50,
                             skip_existing_chunks=False)]
        item = 'minecraft:map'
        if self.modifier:
            item = 'minecraft:filled_map'
            functions.append(self.fn('filtered', item_filter={'predicates': {'minecraft:map_id': {}}}, on_fail=self.fn('discard')))
        set_name = self.fn('set_name', name={'translate': f'item.{NS}.trawler_map', 'fallback': 'Bottled Map to a Wreck'})
        if not self.legacy:
            set_name['target'] = 'item_name'
        functions.append(set_name)
        return self.with_functions({'type': 'minecraft:item', 'name': item, 'weight': weight}, functions)

    @staticmethod
    def pool(rolls, entries):
        return {'rolls': Dialect.uniform(*rolls) if isinstance(rolls, tuple) else rolls, 'entries': entries}

    def block_loot(self, block):
        pool = self.with_conditions({'rolls': 1, 'entries': [{'type': 'minecraft:item', 'name': block}]},
                                    [self.cond('survives_explosion')])
        return {'type': 'minecraft:block', 'random_sequence': block.replace(':', ':blocks/'), 'pools': [pool]}

    # Recipes
    def ingredient(self, value):
        if self.v26:
            return value
        return {'tag': value[1:]} if value.startswith('#') else {'item': value}

    def recipe(self, pattern, key, result, count):
        out = {'type': 'minecraft:crafting_shaped' if pattern else 'minecraft:crafting_shapeless', 'category': 'misc'}
        if pattern:
            out['pattern'] = pattern
            out['key'] = {k: self.ingredient(i) for k, i in key.items()}
        else:
            out['ingredients'] = [self.ingredient(i) for i in key]
        out['result'] = {'item': result, 'count': count} if self.legacy else {'id': result, 'count': count}
        return out

    def items_predicate(self, item):
        if self.legacy:
            return {'tag': item[1:]} if item.startswith('#') else {'items': [item]}
        return {'items': item}

    def unlock(self, recipe_id, item):
        return {
            'parent': 'minecraft:recipes/root',
            'criteria': {
                'has_item': {'trigger': 'minecraft:inventory_changed', 'conditions': {'items': [self.items_predicate(item)]}},
                'has_the_recipe': {'trigger': 'minecraft:recipe_unlocked',
                                   'conditions': {('recipes' if self.modifier else 'recipe'): recipe_id}},
            },
            'requirements': [['has_item', 'has_the_recipe']],
            'rewards': {'recipes': [recipe_id]},
        }

    # Advancements
    def icon(self, item):
        item = item if ':' in item else 'minecraft:' + item
        return {'item': item} if self.legacy else {'id': item}

    def background(self):
        return 'minecraft:block/sand' if self.v26 else 'minecraft:textures/block/sand.png'

    def entity_properties(self, predicate):
        if self.modifier:
            return {'type': 'minecraft:entity_properties', 'entity': 'this', 'predicate': predicate}
        return [{'condition': 'minecraft:entity_properties', 'entity': 'this', 'predicate': predicate}]

    def in_structure(self, sid):
        key = 'structure' if self.legacy else 'structures'
        loc = 'minecraft:location' if self.namespaced_predicates else 'location'
        return {'trigger': 'minecraft:location', 'conditions': {'player': self.entity_properties({loc: {key: f'{NS}:{sid}'}})}}

    def has_item(self, item):
        return {'trigger': 'minecraft:inventory_changed', 'conditions': {'items': [self.items_predicate(item)]}}

    def item_trigger(self, trigger, item):
        pred = {'items': [item]} if self.legacy else {'items': item}
        return {'trigger': f'minecraft:{trigger}', 'conditions': {'item': pred}}


def write(path: Path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')


def loot_tables(d: Dialect):
    tables = {}
    for name, pools in LOOT.items():
        out = []
        for p in pools:
            if p[1] == 'map':
                _, _, weight, empty = p
                out.append(d.pool(1, [d.trawler_map(weight), {'type': 'minecraft:empty', 'weight': empty}]))
            else:
                out.append(d.pool(p[0], [d.item(x) for x in p[1]]))
        tables[name] = {'type': 'minecraft:chest', 'pools': out}
    tables['gameplay/crab_pot/junk'] = {'type': 'minecraft:fishing', 'pools': [d.pool(1, [d.item(x) for x in POT_JUNK])]}
    tables['gameplay/crab_pot/treasure'] = {'type': 'minecraft:fishing', 'pools': [d.pool(1, [d.item(x) for x in POT_TREASURE])]}
    for place, extras in POT_EXTRAS.items():
        entries = [d.table_ref('minecraft:gameplay/fishing/fish', 70, -1),
                   d.table_ref(f'{NS}:gameplay/crab_pot/junk', 14, -2),
                   d.table_ref(f'{NS}:gameplay/crab_pot/treasure', 3, 2)]
        entries += [d.item(x) for x in extras]
        tables[f'gameplay/crab_pot/{place}'] = {'type': 'minecraft:fishing', 'pools': [d.pool(1, entries)]}
    tables['gameplay/message_in_a_bottle'] = {'type': 'minecraft:gift', 'pools': [
        d.pool(1, [d.trawler_map(BOTTLE_MAP_WEIGHT)] + [d.item(x) for x in BOTTLE])]}
    rod = d.with_conditions(d.pool(1, [{'type': 'minecraft:item', 'name': f'{NS}:message_in_a_bottle'}]),
                            [d.cond('random_chance', chance=ROD_BOTTLE_CHANCE)])
    tables['gameplay/rod_extras'] = {'type': 'minecraft:fishing', 'pools': [rod]}
    for item in ('crab_pot', 'fishing_net'):
        tables[f'blocks/{item}'] = d.block_loot(f'{NS}:{item}')
    return tables


def advancements(d: Dialect, lang):
    out = {}

    def display(name, item, title, desc, frame='task', root=False):
        lang[f'advancements.{NS}.{name}.title'] = title
        lang[f'advancements.{NS}.{name}.description'] = desc
        shown = {'icon': d.icon(item), 'title': {'translate': f'advancements.{NS}.{name}.title', 'fallback': title},
                 'description': {'translate': f'advancements.{NS}.{name}.description', 'fallback': desc}, 'frame': frame,
                 'show_toast': not root, 'announce_to_chat': not root and frame != 'task'}
        if root:
            shown['background'] = d.background()
        return shown

    ids = list(STRUCTURES)
    root_criteria = {k: d.in_structure(k) for k in ids}
    root_criteria.update({'pot': d.has_item(f'{NS}:crab_pot'), 'bottle': d.has_item(f'{NS}:message_in_a_bottle')})
    out['root'] = {'display': display('root', f'{NS}:crab_pot', "Fisherman's Coast",
                                      'Meet the fishermen of the coast and fish their waters', root=True),
                   'criteria': root_criteria, 'requirements': [list(root_criteria)]}
    for k, (name, _b, _s, _p, _salt, icon, title, desc) in STRUCTURES.items():
        frame = 'goal' if k in ('lighthouse', 'sunken_trawler') else 'task'
        out[f'discover_{k}'] = {'parent': f'{NS}:root', 'display': display(f'discover_{k}', icon, title, desc, frame),
                                'criteria': {'entered': d.in_structure(k)}, 'requirements': [['entered']]}
    out['get_crab_pot'] = {'parent': f'{NS}:root', 'display': display('get_crab_pot', f'{NS}:crab_pot', 'Pot Luck',
                                                                     'Get a Crab Pot'),
                           'criteria': {'pot': d.has_item(f'{NS}:crab_pot')}, 'requirements': [['pot']]}
    out['buy_crab_pot'] = {'parent': f'{NS}:get_crab_pot',
                           'display': display('buy_crab_pot', 'emerald', 'Tools of the Trade', 'Buy a Crab Pot from a resident fisherman'),
                           'criteria': {'bought': d.item_trigger('villager_trade', f'{NS}:crab_pot')}, 'requirements': [['bought']]}
    out['open_bottle'] = {'parent': f'{NS}:root',
                          'display': display('open_bottle', f'{NS}:message_in_a_bottle', 'Message Received',
                                             'Open a Message in a Bottle', 'goal'),
                          'criteria': {'opened': d.item_trigger('consume_item', f'{NS}:message_in_a_bottle')},
                          'requirements': [['opened']], 'rewards': {'experience': 20}}
    out['all_structures'] = {'parent': f'{NS}:root',
                             'display': display('all_structures', 'spyglass', 'Coastal Wanderer',
                                                "Visit all seven of the coast's places", 'challenge'),
                             'criteria': {k: d.in_structure(k) for k in ids}, 'requirements': [[k] for k in ids],
                             'rewards': {'experience': 250}}
    return out


def structure_json(sid, meta):
    name, biomes, spacing, separation, salt, *_ = STRUCTURES[sid]
    s = meta[sid]
    site = {k: s[k] for k in ('mode', 'max_slope', 'min_depth', 'max_depth', 'max_above_sea', 'any_wet', 'y_offset', 'max_rise')
            if k in s}
    return {'type': f'{NS}:coastal', 'biomes': f'#{NS}:has_structure/{sid}', 'step': 'surface_structures',
            'spawn_overrides': {}, 'terrain_adaptation': 'none', 'template': f'{NS}:{TEMPLATES.get(sid, sid)}', 'config_name': sid,
            'site': site, 'anchor': s['anchor'], 'dry': s['dry'], 'wet': s['wet'], 'around': s['around'],
            'search': s.get('search', 1)}


