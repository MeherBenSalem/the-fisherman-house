"""Draws the mod's 16x16 textures from the pixel grids below (one character per pixel, '.' is transparent).

  python3 tools/gen_textures.py      (needs Pillow; writes tools/assets/textures/{block,item}/*.png)
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image

OUT = Path(__file__).resolve().parent / 'assets' / 'textures'


def draw(name, grid, palette):
    rows = [r for r in grid.strip('\n').split('\n')]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), (name, [len(r) for r in rows])
    img = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != '.':
                img.putpixel((x, y), palette[ch])
    path = OUT / f'{name}.png'
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path)


def hexa(code, alpha=255):
    code = code.lstrip('#')
    return tuple(int(code[i:i + 2], 16) for i in (0, 2, 4)) + (alpha,)


